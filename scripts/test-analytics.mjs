import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const code=readFileSync(new URL('../fyndaren-analytics.js',import.meta.url),'utf8');
const calls=[],events={},listeners={},tags=[];
let granted=false;
const window={FyndarenConsent:{allowed:k=>k==='analytics'&&granted},addEventListener:(k,v)=>events[k]=v};
const document={referrer:'https://www.google.se/search?q=secret',cookie:'',head:{append:t=>tags.push(t)},addEventListener:(k,v)=>listeners[k]=v};
const location={pathname:'/fynd/sample-123/',search:'?email=secret@example.com',origin:'https://fyndaren.se',hostname:'fyndaren.se'};
vm.runInNewContext(code,{window,document,location,navigator:{userAgent:'iPhone'},URL,URLSearchParams,fetch:(url,options)=>{calls.push(JSON.parse(options.body));return Promise.resolve();},setInterval:()=>{}});
assert.equal(calls.length,0);
assert.equal(tags.length,0);
window.FyndarenAnalytics.track('shop_click',123);
assert.equal(calls.length,0);
granted=true;events['fyndaren-consent-change']();
assert.equal(calls.length,2);
assert.equal(calls[0].p_event,'page_view');
assert.equal(calls[1].p_event,'product_view');
assert.equal(calls[0].p_source,'google');
assert.equal(calls[0].p_device,'mobile');
assert.equal(calls[0].p_deal,123);
assert.equal(JSON.stringify(calls).includes('secret'),false);
events['fyndaren-consent-change']();
assert.equal(calls.length,2);
window.FyndarenAnalytics.track('shop_click',123);
assert.equal(calls.length,3);
granted=false;events['fyndaren-consent-change']();
window.FyndarenAnalytics.track('shop_click',123);
assert.equal(calls.length,3);
assert.equal(tags.length,0);
console.log('Analytics consent tests passed');
